String tr(WidgetRef ref, String key, {Map<String, String> args = const {}}) {
  final lang = ref.watch(localeProvider);
  return _fill(_s[lang]?[key] ?? _s['ar']![key] ?? key, args);
}

String trOf(String lang, String key, {Map<String, String> args = const {}}) =>
    _fill(_s[lang]?[key] ?? _s['ar']![key] ?? key, args);

String _fill(String tpl, Map<String, String> args) {
  var s = tpl;
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}
